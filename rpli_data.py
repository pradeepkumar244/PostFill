def _parse(raw):
    rates = {}
    for line in raw.strip().splitlines():
        parts = line.split()
        age, vals = int(parts[0]), [float(v) for v in parts[1:]]
        cols = MATURITY_AGES[len(MATURITY_AGES) - len(vals):]
        rates[age] = dict(zip(cols, vals))
    return rates


